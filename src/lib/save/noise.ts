/** One noise pixel as `getPixel32` returns it: unmultiplied ARGB. */
function noisePixel(rng: Lehmer): number {
  const r = rng.range(0, 255)
  const g = rng.range(0, 255)
  const b = rng.range(0, 255)
  const a = rng.range(0, 255)
  const pm = (c: number) => ((c * a + 127) / 255) | 0
  const f = FLASH_PREMUL_FACTOR[a]
  const un = (c: number) => (c * f + 0x8000) >>> 16
  return ((a << 24) | (un(pm(r)) << 16) | (un(pm(g)) << 8) | un(pm(b))) >>> 0
}

/**
 * `system/Rndm.as`. The noise bitmap is filled lazily: a caller reads the first
 * few pixels of a 200000-pixel image, and every pixel costs four Lehmer steps.
 */
export class Rndm {
  private rng: Lehmer
  private pixels: number[] = []
  private pointer = 0

  constructor(seed: number) {
    // `noise` maps a non-positive seed onto -seed + 1 (operations.rs:200).
    const s = seed | 0
    this.rng = new Lehmer(s <= 0 ? (-s + 1) >>> 0 : s >>> 0)
  }

  /** `Rndm.random()`: advance the pointer, then scale the pixel into [0, 1). */
  random(): number {
    this.pointer = (this.pointer + 1) % 200000
    while (this.pixels.length <= this.pointer) this.pixels.push(noisePixel(this.rng))
    return (this.pixels[this.pointer] * 0.999999999999998 + 1e-15) / 4294967295
  }

  float(low: number, high: number): number {
    return this.random() * (high - low) + low
  }

  /** `Math.floor`, so `integer(2, 4)` yields 2 or 3 and never 4. */
  integer(low: number, high: number): number {
    return Math.floor(this.float(low, high))
  }
}
