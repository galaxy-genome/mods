// Flash Player's BitmapData.noise PRNG, as reimplemented by Ruffle
// (core/src/bitmap/bitmap_data.rs and core/src/bitmap/operations.rs, commit 0c6a734).
// `system/Rndm.as` draws every random number from a 1000x200 noise bitmap, so the
// generator is the player's, not the game's.

/** X_(k+1) = 16807 * X_k mod 2147483647. */
class Lehmer {
  private x: number
  constructor(seed: number) {
    this.x = seed >>> 0
  }
  next(): number {
    this.x = Number((BigInt(this.x) * 16807n) % 2147483647n)
    return this.x
  }
  /** `random_range(low..high)`, inclusive of both ends. */
  range(low: number, high: number): number {
    return low + (this.next() % (high - low + 1))
  }
}

